import { extname } from '@arxhub/path'

const TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json',
  '.md': 'text/markdown; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.svg': 'image/svg+xml',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.pdf': 'application/pdf',
}

// Content type for a published file, by extension. Unknown extensions download as binary rather
// than guessing — the public surface should never sniff.
export function contentTypeFor(pathname: string): string {
  return TYPES[extname(pathname).toLowerCase()] ?? 'application/octet-stream'
}
